def put(p, value):
    if p.runs:
        p.runs[0].text = value
        for run in p.runs[1:]:
            run.text = ''
    else:
        p.add_run(value)

def after(p, text, style='Normal'):
    el = OxmlElement('w:p')
    p._p.addnext(el)
    q = Paragraph(el, p._parent)
    q.style = style
    q.add_run(text)
    return q

def edit(name, changes, additions=()):
    doc = Document(SOURCE / name)
    original = list(doc.paragraphs)
    for i, value in changes.items():
        if i >= len(original):
            raise IndexError((name, i))
        put(original[i], value)
    for i, text in additions:
        after(original[i], text)
    return doc

def save(doc, name):
    path = OUT / name
    doc.save(path)
    print(path)

