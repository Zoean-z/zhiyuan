def put(p,s):
 if p.runs:
  p.runs[0].text=s
  for r in p.runs[1:]:r.text=''
 else:p.add_run(s)
def patch(name, paragraphs, cells=()):
 path=base/name;d=Document(path)
 for p in d.paragraphs:
  for prefix,replacement in paragraphs:
   if p.text.startswith(prefix):put(p,replacement);break
 for ti,ri,ci,val in cells:d.tables[ti].rows[ri].cells[ci].text=val
 d.save(path);print('patched',name)

